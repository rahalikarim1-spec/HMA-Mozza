/**
 * Lists EVERY Thai and Arabic string (all sources) that needs native review -> NATIVE_REVIEW.md
 *   npm run review-strings
 */
import { writeFileSync } from "node:fs";
import { th } from "../src/content/th";
import { ar } from "../src/content/ar";
import { menusUi } from "../src/content/menus-ui";
import { company } from "../src/content/company";
import { landingText, landingUi } from "../src/content/landing";
import { reservationUi } from "../src/content/reservation-ui";
import descriptions from "../src/data/menus/descriptions.i18n.json";

type Entry = [string, string];
const SAMPLE_LANDING = { names: { vegetarian: ["<dish A>", "<dish B>"], pork: ["<dish C>"], priceMin: 100, priceMax: 900, count: 12, branches: ["<branch A>", "<branch B>"] } };

function flatten(value: unknown, path: string, out: Entry[]) {
  if (typeof value === "string") out.push([path, value]);
  else if (typeof value === "function") {
    const f = value as (...a: unknown[]) => unknown;
    const tries: unknown[][] = [[SAMPLE_LANDING], ["<sample>"], [1, 2], ["<a>", "<b>"], [3, "<z>"], [1]];
    for (const args of tries) {
      try {
        const r = f(...args);
        if (typeof r === "string" || Array.isArray(r)) {
          flatten(r, `${path}()`, out);
          return;
        }
      } catch {
        /* try next */
      }
    }
  } else if (Array.isArray(value)) value.forEach((v, i) => flatten(v, `${path}[${i}]`, out));
  else if (value && typeof value === "object")
    for (const [k, v] of Object.entries(value)) flatten(v, path ? `${path}.${k}` : k, out);
}

function section(title: string, dict: unknown) {
  const out: Entry[] = [];
  flatten(dict, "", out);
  const rows = out
    .filter(([k]) => !/^(htmlLang|dir)$/.test(k))
    .map(([k, v]) => `| \`${k}\` | ${v.replace(/\|/g, "\\|").replace(/\n/g, " ")} |`);
  return `## ${title} (${rows.length} strings)\n\n<!-- NEEDS NATIVE REVIEW -->\n\n| Key | Text |\n|---|---|\n${rows.join("\n")}\n`;
}

const desc = (l: "th" | "ar") => Object.fromEntries(Object.entries(descriptions).map(([, v], i) => [`desc[${i}]`, v[l]]));
const pick = <T extends Record<string, unknown>>(o: T, l: "th" | "ar") => o[l];

let md = `# Strings that NEED NATIVE REVIEW

Generated by \`npm run review-strings\` from the dictionaries in \`src/content/\` and \`src/data/menus/descriptions.i18n.json\`.
Do not edit by hand — edit the sources and re-run. Dish **names** are intentionally not translated (kept as printed on the menus).
A shorter first-pass list for Thai is in \`NATIVE_REVIEW_PRIORITY.md\`.

`;
for (const [code, label, dict] of [["th", "Thai (th)", th], ["ar", "Arabic (ar)", ar]] as const) {
  md += `# ${label}\n\n`;
  md += section(`${label} — site dictionary (nav, home, branches, FAQ, common)`, dict) + "\n";
  md += section(`${label} — menus UI`, pick(menusUi as never, code)) + "\n";
  md += section(`${label} — menu dish descriptions`, desc(code)) + "\n";
  md += section(`${label} — SEO landing pages (pizza, pasta, celebrations)`, { text: pick(landingText as never, code), ui: pick(landingUi as never, code) }) + "\n";
  md += section(`${label} — company pages, blog, 404, footer`, pick(company as never, code)) + "\n";
  md += section(`${label} — reservation flow`, pick(reservationUi as never, code)) + "\n";
}
writeFileSync("NATIVE_REVIEW.md", md);
console.log("Wrote NATIVE_REVIEW.md");
