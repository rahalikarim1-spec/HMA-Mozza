/**
 * Lists every Thai and Arabic string that needs native review and writes NATIVE_REVIEW.md.
 *   npm run review-strings
 */
import { writeFileSync } from "node:fs";
import { th } from "../src/content/th";
import { ar } from "../src/content/ar";

type Entry = [string, string];

function flatten(value: unknown, path: string, out: Entry[]) {
  if (typeof value === "string") out.push([path, value]);
  else if (typeof value === "function") {
    // dictionary helper functions: render with a sample argument
    out.push([`${path}("<sample>")`, String((value as (a: string) => string)("<sample>"))]);
  } else if (Array.isArray(value)) value.forEach((v, i) => flatten(v, `${path}[${i}]`, out));
  else if (value && typeof value === "object")
    for (const [k, v] of Object.entries(value)) flatten(v, path ? `${path}.${k}` : k, out);
}

function section(title: string, dict: unknown) {
  const out: Entry[] = [];
  flatten(dict, "", out);
  const rows = out
    .filter(([k]) => !/^(htmlLang|dir)$/.test(k))
    .map(([k, v]) => `| \`${k}\` | ${v.replace(/\|/g, "\\|")} |`);
  return `## ${title} (${rows.length} strings)\n\n<!-- NEEDS NATIVE REVIEW -->\n\n| Key | Text |\n|---|---|\n${rows.join("\n")}\n`;
}

const md = `# Strings that NEED NATIVE REVIEW

Generated by \`npm run review-strings\` from \`src/content/th.ts\` and \`src/content/ar.ts\`.
Do not edit by hand - edit the dictionaries and re-run.

${section("Thai (th)", th)}
${section("Arabic (ar)", ar)}`;

writeFileSync("NATIVE_REVIEW.md", md);
console.log("Wrote NATIVE_REVIEW.md");
